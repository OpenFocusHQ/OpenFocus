package org.openfocus.app.ui.pixel

import androidx.annotation.DrawableRes
import androidx.compose.ui.unit.IntOffset
import org.openfocus.app.R

/** One row of a sprite sheet. */
data class SpriteAnim(val row: Int, val frames: Int, val fps: Float = 4f)

/**
 * A fixed-grid sprite sheet stored in res/drawable-nodpi (so Android never rescales it).
 * Frames are [frameWidth] x [frameHeight] pixels; one row per animation.
 *
 * [anchors] are per-frame pixel offsets other layers can follow, e.g. "head" lets a hat bob
 * with the body. Each anchor list is indexed by frame of the given animation.
 */
data class SpriteSheet(
    @DrawableRes val resId: Int,
    val frameWidth: Int,
    val frameHeight: Int,
    val anims: Map<String, SpriteAnim>,
    val anchors: Map<String, Map<String, List<IntOffset>>> = emptyMap(),
) {
    fun anim(name: String): SpriteAnim = anims[name] ?: anims.values.first()
    fun anchor(anchor: String, anim: String, frame: Int): IntOffset =
        anchors[anchor]?.get(anim)?.let { it[frame.coerceIn(0, it.lastIndex)] } ?: IntOffset.Zero
}

/**
 * Registry of all pixel-art sheets. Keys for cosmetics are [org.openfocus.app.core.ShopItem] ids.
 * Placeholder sheets are generated by art/tools/build_placeholders.py — see art/README.md.
 */
object SpriteCatalog {
    const val IDLE = "idle"
    const val REST = "rest"

    /** Head y-offset per idle frame. MUST match IDLE_BOB in build_placeholders.py. */
    private val HEAD_BOB = listOf(0, 1, 0, 0).map { IntOffset(0, it) }

    private val heroAnims = mapOf(IDLE to SpriteAnim(0, 4, 3f), REST to SpriteAnim(1, 1))

    val heroBody = SpriteSheet(
        R.drawable.px_hero_body, 32, 32, heroAnims,
        anchors = mapOf("head" to mapOf(IDLE to HEAD_BOB, REST to listOf(IntOffset(0, 1)))),
    )

    val cloaks: Map<String, SpriteSheet> = mapOf(
        "color_violet" to SpriteSheet(R.drawable.px_cloak_violet, 32, 32, heroAnims),
        "color_teal" to SpriteSheet(R.drawable.px_cloak_teal, 32, 32, heroAnims),
        "color_ember" to SpriteSheet(R.drawable.px_cloak_ember, 32, 32, heroAnims),
        "color_gold" to SpriteSheet(R.drawable.px_cloak_gold, 32, 32, heroAnims),
    )

    private val still = mapOf(IDLE to SpriteAnim(0, 1))

    val hats: Map<String, SpriteSheet> = mapOf(
        "hat_party" to SpriteSheet(R.drawable.px_hat_party, 32, 32, still),
        "hat_beanie" to SpriteSheet(R.drawable.px_hat_beanie, 32, 32, still),
        "hat_wizard" to SpriteSheet(R.drawable.px_hat_wizard, 32, 32, still),
        "hat_crown" to SpriteSheet(R.drawable.px_hat_crown, 32, 32, still),
    )

    val coin = SpriteSheet(R.drawable.px_coin, 16, 16, mapOf("spin" to SpriteAnim(0, 6, 8f)))

    /** Layers for the hero, bottom to top. Returns null if any required sprite is missing. */
    fun heroLayers(colorId: String?, hatId: String?, anim: String = IDLE): List<SpriteLayer>? {
        val cloak = cloaks[colorId ?: "color_violet"] ?: return null
        val layers = mutableListOf(SpriteLayer(heroBody, anim), SpriteLayer(cloak, anim))
        if (hatId != null) {
            val hat = hats[hatId] ?: return null
            layers += SpriteLayer(hat, IDLE, followAnchor = "head")
        }
        return layers
    }
}
