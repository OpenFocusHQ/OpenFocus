package org.openfocus.app.ui.pixel

import androidx.annotation.DrawableRes
import androidx.compose.ui.unit.IntOffset
import org.openfocus.app.R
import org.openfocus.app.core.Achievements
import org.openfocus.app.core.ShopCatalog
import org.openfocus.app.core.content.EnemyDef
import org.openfocus.app.core.content.ItemDef
import org.openfocus.app.core.content.NpcDef
import org.openfocus.app.core.content.SlotKind

/** An animation: [frames] frames on [row], starting at column [col] (for icon atlases). */
data class SpriteAnim(val row: Int, val frames: Int, val fps: Float = 4f, val col: Int = 0)

/**
 * A fixed-grid sprite sheet stored in res/drawable-nodpi (so Android never rescales it).
 * Frames are [frameWidth] x [frameHeight] pixels; one row per animation.
 *
 * [anchors] are per-frame pixel offsets other layers can follow, e.g. "head" lets a hat bob
 * with the body: anchors[name][anim][frame].
 */
data class SpriteSheet(
    @DrawableRes val resId: Int,
    val frameWidth: Int,
    val frameHeight: Int,
    val anims: Map<String, SpriteAnim>,
    val anchors: Map<String, Map<String, List<IntOffset>>> = emptyMap(),
) {
    fun anim(name: String): SpriteAnim = anims[name] ?: anims.values.first()
    fun anchor(anchor: String, anim: String, frame: Int): IntOffset =
        anchors[anchor]?.get(anim)?.let { it[frame.coerceIn(0, it.lastIndex)] } ?: IntOffset.Zero
}

enum class HeroPose(val anim: String) { IDLE("idle"), REST("rest"), CELEBRATE("celebrate") }

enum class SkinTone(val id: String, val label: String) {
    LIGHT("light", "Light"), MEDIUM("medium", "Medium"), DEEP("deep", "Deep");

    companion object {
        fun of(id: String?) = entries.firstOrNull { it.id == id } ?: LIGHT
    }
}

/**
 * Registry of all pixel-art sheets. Keys for cosmetics are [org.openfocus.app.core.ShopItem] ids.
 * Placeholder sheets are generated by art/tools/build_placeholders.py — see art/README.md.
 */
object SpriteCatalog {
    const val IDLE = "idle"
    const val REST = "rest"
    const val CELEBRATE = "celebrate"
    const val CLIMBING = "climbing"
    const val SUMMIT = "summit"
    const val NIGHT = "night"
    const val CLIMBING_NIGHT = "climbing_night"
    const val SUMMIT_NIGHT = "summit_night"
    const val UNLIT = "unlit"
    const val LIT = "lit"
    const val RED = "red"
    const val GOLD = "gold"

    /** Head y-offsets per frame. MUST match IDLE_BOB / CELEBRATE_JUMP in build_placeholders.py. */
    private val HEAD = mapOf(
        IDLE to listOf(0, 1, 0, 0).map { IntOffset(0, it) },
        REST to listOf(IntOffset(0, 1)),
        CELEBRATE to listOf(IntOffset(0, 0), IntOffset(0, -1)),
    )

    /** Torso offsets: still while idle/resting, hops with the celebrate jump (armour follows this). */
    private val TORSO = mapOf(
        IDLE to List(4) { IntOffset.Zero },
        REST to listOf(IntOffset.Zero),
        CELEBRATE to listOf(IntOffset(0, 0), IntOffset(0, -1)),
    )

    private val heroAnims = mapOf(
        IDLE to SpriteAnim(0, 4, 3f),
        REST to SpriteAnim(1, 1),
        CELEBRATE to SpriteAnim(2, 2, 4f),
    )

    val bodies: Map<SkinTone, SpriteSheet> = mapOf(
        SkinTone.LIGHT to SpriteSheet(R.drawable.px_hero_body_light, 32, 32, heroAnims, mapOf("head" to HEAD, "body" to TORSO)),
        SkinTone.MEDIUM to SpriteSheet(R.drawable.px_hero_body_medium, 32, 32, heroAnims, mapOf("head" to HEAD, "body" to TORSO)),
        SkinTone.DEEP to SpriteSheet(R.drawable.px_hero_body_deep, 32, 32, heroAnims, mapOf("head" to HEAD, "body" to TORSO)),
    )
    val heroBody: SpriteSheet get() = bodies.getValue(SkinTone.LIGHT)

    private val still = mapOf(IDLE to SpriteAnim(0, 1))

    private fun named(name: String, fw: Int, fh: Int, anims: Map<String, SpriteAnim>): SpriteSheet? =
        SpriteRegistry.sprites[name]?.let { SpriteSheet(it.resId, fw, fh, anims) }

    /** A round 48x48 backdrop; a second row (if present) is its dark-theme version. */
    fun backdropSheet(name: String, frames: Int = 1, fps: Float = 1f): SpriteSheet? {
        val info = SpriteRegistry.sprites[name] ?: return null
        val anims = buildMap {
            put(IDLE, SpriteAnim(0, frames.coerceAtLeast(1), fps))
            if (info.height >= 96) put(NIGHT, SpriteAnim(1, 1))
        }
        return SpriteSheet(info.resId, 48, 48, anims)
    }

    /** The sheet for a cosmetic item, shaped by its slot's kind; null if its art doesn't exist yet. */
    fun itemSheet(item: ItemDef): SpriteSheet? {
        val name = item.sprite ?: return null
        return when (ShopCatalog.slot(item.slot)?.kind ?: return null) {
            SlotKind.BODY -> named(name, 32, 32, heroAnims)
            SlotKind.OVERLAY -> named(name, 32, 32, still)
            SlotKind.BACKDROP -> backdropSheet(name, item.frames, item.fps)
        }
    }

    /** 32x32 NPC portrait from content.json (`npcs[].sprite`). */
    fun npcSheet(npc: NpcDef): SpriteSheet? = npc.sprite?.let { named(it, 32, 32, still) }

    /** 48x48 enemy with a two-frame idle bob (`enemies[].sprite`). */
    fun enemySheet(enemy: EnemyDef): SpriteSheet? = enemy.sprite?.let { named(it, 48, 48, mapOf(IDLE to SpriteAnim(0, 2, 2f))) }

    /** Backdrop shown when none is equipped. */
    val defaultBackdrop: SpriteSheet?
        get() = ShopCatalog.slots.firstOrNull { it.kind == SlotKind.BACKDROP }?.defaultSprite?.let { backdropSheet(it) }

    /** Where the 32x32 hero stands inside a 48x48 backdrop. */
    val HERO_IN_BACKDROP = IntOffset(8, 13)

    /** Goal ascent scenes, indexed by goal colorIndex (see PaletteColors). */
    val ascents: List<SpriteSheet> = listOf(
        R.drawable.px_ascent_0, R.drawable.px_ascent_1, R.drawable.px_ascent_2, R.drawable.px_ascent_3,
        R.drawable.px_ascent_4, R.drawable.px_ascent_5, R.drawable.px_ascent_6, R.drawable.px_ascent_7,
    ).map {
        SpriteSheet(
            it, 160, 112,
            mapOf(CLIMBING to SpriteAnim(0, 1), SUMMIT to SpriteAnim(1, 1), CLIMBING_NIGHT to SpriteAnim(2, 1), SUMMIT_NIGHT to SpriteAnim(3, 1)),
        )
    }

    fun ascent(colorIndex: Int): SpriteSheet = ascents[((colorIndex % ascents.size) + ascents.size) % ascents.size]

    val tent = SpriteSheet(R.drawable.px_tent, 8, 8, mapOf(UNLIT to SpriteAnim(0, 1), LIT to SpriteAnim(1, 2, 3f)))
    val climber = SpriteSheet(R.drawable.px_climber, 10, 12, mapOf(IDLE to SpriteAnim(0, 2, 2f)))
    val flag = SpriteSheet(R.drawable.px_flag, 8, 8, mapOf(RED to SpriteAnim(0, 2, 3f), GOLD to SpriteAnim(1, 2, 3f)))

    /**
     * 24x24 achievement badges, 5 per row, in [Achievements.all] order; animation name = achievement id.
     * MUST match BADGES order in build_placeholders.py (checked by SpriteCatalogTest).
     */
    const val BADGE_COLUMNS = 5
    val badges = SpriteSheet(
        R.drawable.px_badges, 24, 24,
        Achievements.all.mapIndexed { i, a -> a.id to SpriteAnim(i / BADGE_COLUMNS, 1, col = i % BADGE_COLUMNS) }.toMap(),
    )

    /** 48x48 sparkle burst; overlays a hero avatar (same logical size, so same pixel scale). */
    val sparkle = SpriteSheet(R.drawable.px_sparkle, 48, 48, mapOf(IDLE to SpriteAnim(0, 8, 10f)))

    /** Block-screen shield, 48x48, breathing glow (4 frames @ 1 fps = one 4 s breath). */
    val shield = SpriteSheet(R.drawable.px_shield, 48, 48, mapOf(IDLE to SpriteAnim(0, 4, 1f)))

    /** 64x48 empty-state scenes. MUST match EMPTY_SCENES order in build_placeholders.py. */
    const val EMPTY_QUESTS = "quests"
    const val EMPTY_HABITS = "habits"
    const val EMPTY_GOALS = "goals"
    val empty = SpriteSheet(
        R.drawable.px_empty, 64, 48,
        listOf(EMPTY_QUESTS, EMPTY_HABITS, EMPTY_GOALS).mapIndexed { i, n -> n to SpriteAnim(0, 1, col = i) }.toMap(),
    )

    val coin = SpriteSheet(R.drawable.px_coin, 16, 16, mapOf("spin" to SpriteAnim(0, 6, 8f)))

    /**
     * Layers for the hero, bottom to top, following the content's slot layers (the body sits at
     * layer 1). Returns null if anything equipped has no sprite yet, so the caller can fall back to
     * the shape-drawn hero.
     * @param equipped slot id -> item id (defaults for required slots are filled in).
     */
    fun heroLayers(
        equipped: Map<String, String>,
        pose: HeroPose = HeroPose.IDLE,
        skin: SkinTone = SkinTone.LIGHT,
        withBackdrop: Boolean = false,
        night: Boolean = false,
    ): List<SpriteLayer>? {
        val body = bodies[skin] ?: return null
        val at = if (withBackdrop) HERO_IN_BACKDROP else IntOffset.Zero
        val eq = ShopCatalog.resolveEquipped(equipped)
        val stack = mutableListOf(BODY_LAYER to SpriteLayer(body, pose.anim, at))
        for (slot in ShopCatalog.slots) {
            val item = ShopCatalog.byId(eq[slot.id])
            when (slot.kind) {
                SlotKind.BACKDROP -> if (withBackdrop) {
                    val bg = if (item != null) itemSheet(item) ?: return null else defaultBackdrop ?: continue
                    stack += slot.layer to SpriteLayer(bg, if (night && NIGHT in bg.anims) NIGHT else IDLE)
                }
                SlotKind.BODY -> if (item != null) stack += slot.layer to SpriteLayer(itemSheet(item) ?: return null, pose.anim, at)
                SlotKind.OVERLAY -> if (item != null) {
                    stack += slot.layer to SpriteLayer(itemSheet(item) ?: return null, IDLE, at, followAnchor = slot.anchor)
                }
            }
        }
        return stack.sortedBy { it.first }.map { it.second }
    }

    /** The hero's own body is drawn at this layer; slots order themselves around it. */
    const val BODY_LAYER = 1
}
